import type { Metadata } from "next";
import { site } from "@/lib/site";

/** Open Graph title used for the home page and as the site-wide default. */
export const DEFAULT_OG_TITLE = "Renovations & Custom Builds in Toronto & the GTA";

const OG_IMAGE_ALT = `${site.name}: renovations and custom builds in Toronto & the GTA`;
const ogImages = [{ url: "/opengraph-image", width: 1200, height: 630, alt: OG_IMAGE_ALT, type: "image/png" }];
const twitterImages = [{ url: "/twitter-image", width: 1200, height: 630, alt: OG_IMAGE_ALT }];

/**
 * Builds per-page metadata. Next.js replaces (rather than merges) a parent's
 * `openGraph` object, so every page gets the full set of Open Graph fields here.
 *
 * Share images are generated by app/opengraph-image.tsx and app/twitter-image.tsx.
 * Because a page's own `openGraph` object replaces the parent's (including file-based
 * images), each page points at those generated routes explicitly. Pass `images` to
 * pageMetadata's result to give a page its own.
 */
export function pageMetadata({ title, description, path }: { title: string; description: string; path: string }): Metadata {
  const isHome = path === "/";
  const ogTitle = isHome ? DEFAULT_OG_TITLE : `${title} | ${site.name}`;
  return {
    title: isHome ? { absolute: title } : title,
    description,
    alternates: { canonical: path },
    openGraph: {
      type: "website",
      locale: "en_CA",
      siteName: site.name,
      url: path,
      title: ogTitle,
      description,
      images: ogImages,
    },
    twitter: {
      card: "summary_large_image",
      title: ogTitle,
      description,
      images: twitterImages,
    },
  };
}
